// Permissions, approval policy and capability dependencies for the 42 skills.
// Approval is decided per action and exact revision on the server; this table
// declares the default policy each action starts from. Separation of duties is
// always on for protected budget, payment, journal and configuration changes.

const none = (en: string, es: string) =>
  ({ mode: "none", separationOfDuties: false, note: { en, es } }) as const
const confirm = (en: string, es: string) =>
  ({ mode: "confirmation", separationOfDuties: false, note: { en, es } }) as const
const finance = (en: string, es: string) =>
  ({
    mode: "approval",
    eligibleRoles: ["finance_approver"],
    separationOfDuties: true,
    note: { en, es },
  }) as const
const ownerOrFinance = (en: string, es: string) =>
  ({
    mode: "approval",
    eligibleRoles: ["owner", "finance_approver"],
    separationOfDuties: true,
    note: { en, es },
  }) as const
const ownerApproval = (en: string, es: string) =>
  ({
    mode: "approval",
    eligibleRoles: ["owner"],
    separationOfDuties: true,
    note: { en, es },
  }) as const

